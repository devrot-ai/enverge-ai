"""LLM-assisted task generation for ForgeLab.

Uses an LLM to generate new task descriptions and scenarios based on
existing templates and mutations. Each generated task is independently
validated before being added to the task pool.

Configuration via environment variables:
    FORGELAB_API_KEY - API key for task generation
    FORGELAB_BASE_URL - API base URL
    FORGELAB_MODEL - Model name for generation

Generated tasks are validated using the existing WorldValidator and
TaskValidator to ensure quality before entering the pool.
"""

from __future__ import annotations

import json
import logging
import os
import uuid
from dataclasses import dataclass, field
from typing import Any

import yaml

from forge.core.schemas import TaskCategory, TaskSpec
from forge.world_factory.templates import list_templates
from forge.world_factory.seeder import list_mutations

logger = logging.getLogger(__name__)


@dataclass
class GeneratedTask:
    """A task generated by an LLM."""

    task_id: str
    template: str
    mutation: str
    category: TaskCategory
    difficulty: int
    description: str
    constraints: str
    capabilities: list[str] = field(default_factory=list)
    verified: bool = False


def _check_llm_available() -> bool:
    """Check if LLM API is available for task generation."""
    api_key = os.environ.get("FORGELAB_API_KEY", "")
    if not api_key:
        return False
    try:
        import openai  # noqa: F401

        return True
    except ImportError:
        return False


class LLMTaskGenerator:
    """Generate new tasks using LLM assistance.

    Uses an LLM to create diverse task scenarios based on existing
    templates and mutations. Each task is validated before being
    added to the pool.
    """

    def __init__(self):
        self._available = _check_llm_available()
        self._client = None
        self._model = os.environ.get("FORGELAB_MODEL", "gpt-4o")

        if self._available:
            try:
                import openai

                api_key = os.environ.get("FORGELAB_API_KEY", "")
                base_url = os.environ.get("FORGELAB_BASE_URL")
                self._client = openai.OpenAI(
                    api_key=api_key,
                    base_url=base_url,
                )
                logger.info("LLM task generator initialized with model %s", self._model)
            except Exception as e:
                logger.warning("Failed to initialize LLM task generator: %s", e)
                self._available = False

    def generate_tasks(
        self,
        template: str | None = None,
        count: int = 5,
        difficulty_range: tuple[int, int] = (1, 5),
    ) -> list[GeneratedTask]:
        """Generate tasks using LLM.

        Args:
            template: Optional template to generate tasks for.
            count: Number of tasks to generate.
            difficulty_range: Min and max difficulty levels.

        Returns:
            List of generated tasks.
        """
        if not self._available:
            logger.warning(
                "LLM API not available. Use `forgelab task variants` for "
                "template-based generation instead."
            )
            return []

        templates = list_templates()
        mutations = list_mutations()

        # Build context for the LLM
        template_info = ""
        if template:
            template_info = f"Focus on template: {template}"
            available_mutations = [m for m in mutations if m.get("template") == template]
        else:
            available_mutations = mutations
            template_info = f"Available templates: {', '.join(templates)}"

        mutation_info = "\n".join(
            f"- {m.get('name', 'unknown')}: {m.get('description', '')}"
            for m in available_mutations[:20]
        )

        prompt = f"""Generate {count} software engineering bug-fix tasks for testing AI agents.

{template_info}

Available mutation types:
{mutation_info}

Each task should describe a realistic bug scenario. Tasks should vary in:
- Bug type (logic error, edge case, security vulnerability, etc.)
- Complexity (from simple typo to multi-file refactoring)
- Required skills (debugging, testing, code review, etc.)

Difficulty range: {difficulty_range[0]}-{difficulty_range[1]}

Return a JSON array with this schema:
[
  {{
    "template": "template_name",
    "mutation": "mutation_name",
    "category": "bug_fixing|edge_case_debugging|security_vulnerability|refactoring|performance_optimization",
    "difficulty": 3,
    "description": "Detailed description of the bug and what needs to be fixed...",
    "constraints": "Any constraints on how the fix should be implemented...",
    "capabilities": ["debugging", "code_analysis"]
  }}
]

Generate exactly {count} tasks with diverse scenarios."""

        try:
            response = self._client.chat.completions.create(
                model=self._model,
                messages=[
                    {"role": "system", "content": "You are a software engineering expert who creates bug-fix tasks for testing AI coding agents."},
                    {"role": "user", "content": prompt},
                ],
                temperature=0.7,
                max_tokens=4096,
            )

            content = response.choices[0].message.content or ""
            # Extract JSON from response
            start = content.find("[")
            end = content.rfind("]") + 1
            if start != -1 and end != 0:
                tasks_data = json.loads(content[start:end])
            else:
                tasks_data = json.loads(content)

            tasks = []
            for item in tasks_data:
                task = GeneratedTask(
                    task_id=f"task-llm-{uuid.uuid4().hex[:8]}",
                    template=item.get("template", template or "task_manager_api"),
                    mutation=item.get("mutation", ""),
                    category=TaskCategory(item.get("category", "bug_repair")),
                    difficulty=max(1, min(5, item.get("difficulty", 3))),
                    description=item.get("description", ""),
                    constraints=item.get("constraints", ""),
                    capabilities=item.get("capabilities", []),
                )
                tasks.append(task)

            logger.info("Generated %d tasks via LLM", len(tasks))
            return tasks

        except Exception as e:
            logger.error("LLM task generation failed: %s", e)
            return []

    def generate_from_seed(
        self, seed_task: dict[str, Any], variations: int = 3
    ) -> list[GeneratedTask]:
        """Generate variations of a seed task.

        Args:
            seed_task: A seed task dictionary.
            variations: Number of variations to generate.

        Returns:
            List of task variations.
        """
        if not self._available:
            return []

        prompt = f"""Create {variations} variations of this bug-fix task:

Template: {seed_task.get('template', 'unknown')}
Mutation: {seed_task.get('mutation', 'unknown')}
Original: {seed_task.get('description', '')}

Each variation should test a similar skill but with a different scenario.
Make them progressively more difficult.

Return a JSON array with the same schema as before."""

        try:
            response = self._client.chat.completions.create(
                model=self._model,
                messages=[
                    {"role": "system", "content": "You create variations of coding tasks."},
                    {"role": "user", "content": prompt},
                ],
                temperature=0.8,
                max_tokens=2048,
            )

            content = response.choices[0].message.content or ""
            start = content.find("[")
            end = content.rfind("]") + 1
            if start != -1 and end != 0:
                tasks_data = json.loads(content[start:end])
            else:
                tasks_data = json.loads(content)

            tasks = []
            for i, item in enumerate(tasks_data):
                task = GeneratedTask(
                    task_id=f"task-llm-var-{uuid.uuid4().hex[:8]}",
                    template=item.get("template", seed_task.get("template", "")),
                    mutation=item.get("mutation", seed_task.get("mutation", "")),
                    category=TaskCategory(item.get("category", seed_task.get("category", "bug_repair"))),
                    difficulty=max(1, min(5, seed_task.get("difficulty", 3) + i)),
                    description=item.get("description", ""),
                    constraints=item.get("constraints", ""),
                    capabilities=item.get("capabilities", []),
                )
                tasks.append(task)

            return tasks

        except Exception as e:
            logger.error("LLM variation generation failed: %s", e)
            return []

    def save_tasks(self, tasks: list[GeneratedTask], path: str) -> None:
        """Save generated tasks to a YAML file.

        Args:
            tasks: List of generated tasks.
            path: Output file path.
        """
        data = {
            "generated_tasks": [
                {
                    "task_id": t.task_id,
                    "template": t.template,
                    "mutation": t.mutation,
                    "category": t.category.value,
                    "difficulty": t.difficulty,
                    "description": t.description,
                    "constraints": t.constraints,
                    "capabilities": t.capabilities,
                }
                for t in tasks
            ]
        }

        with open(path, "w") as f:
            yaml.dump(data, f, default_flow_style=False)

        logger.info("Saved %d tasks to %s", len(tasks), path)

    def to_task_specs(self, tasks: list[GeneratedTask]) -> list[TaskSpec]:
        """Convert generated tasks to TaskSpec objects.

        Args:
            tasks: List of generated tasks.

        Returns:
            List of TaskSpec objects.
        """
        specs = []
        for t in tasks:
            spec = TaskSpec(
                task_id=t.task_id,
                world_id=f"world-{t.template}-{t.mutation}",
                description=t.description,
                category=t.category,
                difficulty_level=t.difficulty,
                constraints=t.constraints,
                capabilities=t.capabilities,
                verification_method="test_execution",
            )
            specs.append(spec)
        return specs
